const languageButtons = document.querySelectorAll("[data-lang]");
const translatedElements = document.querySelectorAll("[data-i18n]");

function setLanguage(language, updateUrl = true) {
  const selectedLanguage = translations[language] ? language : "en";
  const strings = translations[selectedLanguage];

  document.documentElement.lang = selectedLanguage;
  document.title = strings.documentTitle;

  translatedElements.forEach((element) => {
    const key = element.dataset.i18n;
    if (strings[key]) element.textContent = strings[key];
  });

  languageButtons.forEach((button) => {
    button.setAttribute("aria-pressed", String(button.dataset.lang === selectedLanguage));
  });

  if (updateUrl) {
    const url = new URL(window.location.href);
    url.searchParams.set("lang", selectedLanguage);
    window.history.replaceState({}, "", url);
  }
}

languageButtons.forEach((button) => {
  button.addEventListener("click", () => setLanguage(button.dataset.lang));
});

const requestedLanguage = new URLSearchParams(window.location.search).get("lang");
const browserLanguage = navigator.language.toLowerCase().startsWith("ru") ? "ru" : "en";
setLanguage(requestedLanguage || browserLanguage, Boolean(requestedLanguage));

